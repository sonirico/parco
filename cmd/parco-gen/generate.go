package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"sort"
	"strings"
	"text/template"
)

const parcoImport = "github.com/sonirico/parco"

type field struct {
	Name string
	wire
}

type model struct {
	Name   string
	Func   string
	Fields []field
}

type file struct {
	Package string
	Imports []string
	Models  []model
}

var tmpl = template.Must(template.New("parco").Parse(`// Code generated by parco-gen. DO NOT EDIT.

//go:build go1.27

package {{.Package}}

import (
{{- range .Imports}}
	"{{.}}"
{{- end}}
)
{{range $m := .Models}}
func {{$m.Func}}() *parco.Model[{{$m.Name}}] {
	return parco.NewModel[{{$m.Name}}](parco.ObjectFactory[{{$m.Name}}]()).
{{- range $i, $f := $m.Fields}}{{if $i}}.{{end}}
		Field({{$f.TypeExpr}},
			func(x *{{$m.Name}}) {{$f.ValueTyp}} { {{$f.Get}} },
			func(x *{{$m.Name}}, v {{$f.ValueTyp}}) { {{$f.Set}} })
{{- end}}
}
{{end}}`))

func (w wire) TypeExpr() string { return w.typeExpr }
func (w wire) ValueTyp() string { return w.valueTyp }
func (w wire) Get() string      { return w.get }
func (w wire) Set() string      { return w.set }

func generate(dir string, names []string) ([]byte, error) {
	src, err := parseSource(dir)
	if err != nil {
		return nil, err
	}
	if names == nil {
		names = src.tagged()
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("no struct with a parco tag in %s", dir)
	}

	out := file{Package: src.pkg}
	imports := map[string]bool{parcoImport: true}
	for _, name := range names {
		st, ok := src.structs[name]
		if !ok {
			return nil, fmt.Errorf("struct %s not found in %s", name, dir)
		}
		m, err := src.model(name, st, imports)
		if err != nil {
			return nil, err
		}
		out.Models = append(out.Models, m)
	}
	for path := range imports {
		out.Imports = append(out.Imports, path)
	}
	sort.Strings(out.Imports)

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, out); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}

// tagged lists, in declaration order, every struct with a parco tag on at
// least one field.
func (s *source) tagged() []string {
	var names []string
	for _, name := range s.order {
		for _, f := range s.structs[name].Fields.List {
			if f.Tag != nil && strings.Contains(f.Tag.Value, `parco:"`) {
				names = append(names, name)
				break
			}
		}
	}
	return names
}

func (s *source) model(name string, st *ast.StructType, imports map[string]bool) (model, error) {
	m := model{Name: name, Func: modelFunc(name)}
	for _, f := range st.Fields.List {
		var opts tagOptions
		if f.Tag != nil {
			var err error
			if opts, err = parseTag(strings.Trim(f.Tag.Value, "`")); err != nil {
				return m, fmt.Errorf("%s: %w", name, err)
			}
		}
		if opts.skip {
			continue
		}
		if len(f.Names) == 0 {
			return m, fmt.Errorf("%s: embedded fields are not supported", name)
		}
		for _, ident := range f.Names {
			w, err := s.wireOf(ident.Name, f.Type, opts)
			if err != nil {
				return m, fmt.Errorf("%s.%s: %w", name, ident.Name, err)
			}
			m.Fields = append(m.Fields, field{Name: ident.Name, wire: w})
		}
		s.collectImports(f.Type, imports)
	}
	return m, nil
}

func (s *source) collectImports(expr ast.Expr, imports map[string]bool) {
	ast.Inspect(expr, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		if pkg, ok := sel.X.(*ast.Ident); ok {
			if path, ok := s.imports[pkg.Name]; ok {
				imports[path] = true
			}
		}
		return true
	})
}
